-- updated_at diisi trigger, bukan oleh aplikasi.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = pg_catalog.now();
  return new;
end;
$$;

-- Fungsi trigger hanya dipanggil oleh trigger, bukan lewat /rest/v1/rpc.
revoke execute on function public.set_updated_at() from public, anon, authenticated;

drop trigger if exists artists_set_updated_at on public.artists;
create trigger artists_set_updated_at
  before update on public.artists
  for each row execute function public.set_updated_at();

-- Simpan stat artist secara atomik (update baris + ganti skill dalam satu transaksi).
-- Hanya service_role: dipanggil dari server action yang sudah memeriksa sesi.
create or replace function public.save_artist_stats(
  p_slug text,
  p_name text,
  p_genre text,
  p_origin text,
  p_skills jsonb
) returns integer
language plpgsql
set search_path = ''
as $$
declare
  v_id integer;
  v_origin text := nullif(p_origin, '');
begin
  update public.artists
     set name = p_name,
         genre = p_genre,
         origin = v_origin
   where slug = p_slug
  returning id into v_id;

  if v_id is null then
    raise exception 'artist % not found', p_slug using errcode = 'P0002';
  end if;

  delete from public.artist_skills where artist_id = v_id;

  insert into public.artist_skills (artist_id, slot, effect, value)
  select v_id, (e->>'slot')::smallint, e->>'effect', nullif(e->>'value', '')::integer
    from jsonb_array_elements(coalesce(p_skills, '[]'::jsonb)) e;

  return v_id;
end;
$$;

revoke all on function public.save_artist_stats(text, text, text, text, jsonb) from public, anon, authenticated;
grant execute on function public.save_artist_stats(text, text, text, text, jsonb) to service_role;

