create table public.artists (
  id integer primary key generated by default as identity,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name text not null,
  genre text not null references public.genres (id) on update cascade,
  origin text references public.origins (id) on update cascade,
  -- Skill 1 semua artist: damage flat tiap BASE_SKILL_INTERVAL detik. Tidak dipakai
  -- scoreArtist, jadi tidak memengaruhi tier.
  base_dmg integer not null default 1800 check (base_dmg > 0),
  photo_path text,
  -- Versi cache foto, terpisah dari updated_at supaya edit stat tidak memicu unduh ulang gambar.
  photo_updated_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Id hero di config game (CHeroData.Id) sebagai sumber data biaya level; null = belum dipetakan.
  game_hero_id integer unique
);

create table public.artist_skills (
  artist_id integer not null references public.artists (id) on delete cascade,
  -- Slot 1 = base_dmg di tabel artists; slot 2 & 3 = skill dari config game.
  slot smallint not null check (slot between 2 and 3),
  effect text not null references public.effects (id) on update cascade,
  value integer check (value > 0),
  primary key (artist_id, slot)
);

-- Biaya EXP naik level artis 1..160, sumber tabel config CHeroStarLevel.
-- exp_step = tambahan EXP level ini, exp_total = total EXP kumulatif dari level 1.
create table public.artist_level_costs (
  artist_id integer not null references public.artists (id) on delete cascade,
  level smallint not null check (level between 1 and 160),
  star smallint not null check (star >= 0),
  exp_step bigint not null check (exp_step >= 0),
  exp_total bigint not null check (exp_total >= 0),
  primary key (artist_id, level)
);

-- Biaya naik star artis, sumber CHeroStarCard. Baris star N = biaya menuju star N+1.
-- Star 30 adalah batas (tanpa biaya); roster max level 160 butuh star 0..21.
create table public.artist_star_costs (
  artist_id integer not null references public.artists (id) on delete cascade,
  star smallint not null check (star between 0 and 29),
  item_id integer not null,
  item_name text not null,
  amount bigint not null check (amount > 0),
  primary key (artist_id, star, item_id)
);

