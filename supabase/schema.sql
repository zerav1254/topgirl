create table public.genres (
  id text primary key,
  label text not null,
  sort integer not null default 0
);

create table public.regions (
  id text primary key,
  label text not null default '',
  sort integer not null default 0
);

create table public.effects (
  id text primary key,
  label text not null,
  unit text not null default 'percent' check (unit in ('percent', 'flat')),
  sort integer not null default 0
);

create table public.artists (
  id integer primary key generated by default as identity,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name text not null,
  genre text not null references public.genres (id) on update cascade,
  region text references public.regions (id) on update cascade,
  season integer,
  photo_path text,
  updated_at timestamptz not null default now()
);

create table public.artist_skills (
  artist_id integer not null references public.artists (id) on delete cascade,
  slot smallint not null check (slot between 1 and 2),
  effect text not null references public.effects (id) on update cascade,
  value integer check (value > 0),
  primary key (artist_id, slot)
);

create index artist_skills_effect_idx on public.artist_skills (effect);

alter table public.artists enable row level security;
alter table public.artist_skills enable row level security;
alter table public.genres enable row level security;
alter table public.regions enable row level security;
alter table public.effects enable row level security;

